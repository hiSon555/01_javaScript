var sum = 0;
for (var n = 1; n <= 100; n++) {
    sum += n;       // sum + sum + n;
}
console.log(sum);
// 첫번째 사이클 : sum = sum + n;     // sum 0, n 1 = 0 + 1 = 1
// 두번째 사이클 : sum = sum + n;     // sum 1, n 2 = 1 + 2 = 3
// 세번째 사이클 : sum = sum + n;     // sum 3, n 3 = 3 + 3 = 6
// 네번째 사이클 : sum = sum + n;     // sum 6, n 4 = 6 + 4 = 10
// 다섯번째 사이클 :                  // sum 10, n 5 = 10 + 5 = 15
// 여섯번째 사이클 :                  // sum 15, n 6 = 15 + 6 = 21




// 중첩 반복문 : 그냥 for문 안에 for문을 쓰는 것

// 구구단! 2단만 만들어 보면
// 2 * n => n은 1부터 9까지
for (var dan = 2; dan <= 9; dan++) {
    for (k = 1; k <= 9; k++) {
        console.log(`${dan} * ${k} = ${dan * k}`);
    }
}